"""Bake a wall scratch cycle on the accepted cat rig; leave the mesh intact.

Forepaws have IK targets measured in Godot at the wallpaper surface. The
hind paws stay in the neutral grounded pose while one forepaw braces and the
other makes a short downstroke. The recovery lifts away from the wallpaper.
"""
from pathlib import Path
import json
import math
import bpy
from mathutils import Matrix, Vector

ROOT = Path(__file__).resolve().parents[3]
bpy.ops.wm.open_mainfile(filepath=str(Path(__file__).with_name('cat_reference.blend')))
rig = next(o for o in bpy.context.scene.objects if o.type == 'ARMATURE')
rig.animation_data_clear()
for bone in rig.pose.bones:
    bone.matrix_basis = Matrix.Identity(4)
bpy.context.view_layer.update()
rest = {bone.name: bone.matrix.copy() for bone in rig.pose.bones}
MODEL_SCALE=1.65
ROLL=1.05
FORWARD=.39
rear=(rest['leg_back_left_4'].translation+rest['leg_back_right_4'].translation)*.5
model_y=-.06+rear.z*MODEL_SCALE-(math.sin(ROLL)*rear.x+math.cos(ROLL)*rear.z)*MODEL_SCALE
targets = []
for side in ('left', 'right'):
    ankle = rig.pose.bones[f'leg_front_{side}_3']
    marker = bpy.data.objects.new(f'Scratch target {side}', None)
    bpy.context.collection.objects.link(marker)
    ik = ankle.constraints.new('IK')
    ik.target = marker
    ik.chain_count = 3
    targets.append((side, marker))

def ease(t):
    t = max(0., min(1., t))
    return t*t*(3-2*t)

def stroke(phase):
    # High: a brief brace. Downstroke: quick, in contact. Recovery: paw
    # relaxes and retracts from the wallpaper before reaching upward again.
    if phase < .14: return .62, 0.
    if phase < .42: return .62-.14*ease((phase-.14)/.28), 0.
    if phase < .58: return .48, .012*ease((phase-.42)/.16)
    u = (phase-.58)/.42
    return .48+.14*ease(u), .04*math.sin(math.pi*u)**2

frames = []
for frame in range(25):
    t = frame/24
    for bone in rig.pose.bones:
        bone.matrix_basis = Matrix.Identity(4)
    bpy.context.view_layer.update()
    # Small weight shift gives the shoulders room to work while the two hind
    # paws remain fixed. The rig's back legs are separate root chains.
    weight = math.sin(math.tau*t)
    rig.pose.bones['pelvis'].matrix = Matrix.Translation((weight*.004, weight*.004, weight*.003)) @ rest['pelvis']
    bpy.context.view_layer.update()
    for side, marker in targets:
        h, retract = stroke((t + (.5 if side == 'left' else 0.)) % 1.)
        # Invert the actual scaled posture, so the smaller kitten still reaches
        # the same wallpaper plane at z=-4.905 without stretching its legs.
        forward=(.505-FORWARD-retract)/MODEL_SCALE
        up=(h-.06-model_y)/MODEL_SCALE
        toe=Vector((math.cos(ROLL)*forward+math.sin(ROLL)*up,
            .055/MODEL_SCALE if side=='left' else -.055/MODEL_SCALE,
            -math.sin(ROLL)*forward+math.cos(ROLL)*up))
        foot = f'leg_front_{side}_4'
        toe_end = f'{foot}_end'
        ankle_point = toe-(rest[toe_end].translation-rest[foot].translation)
        marker.location = rig.matrix_world @ ankle_point
    tail_pivot = rest['tail_1'].translation
    rig.pose.bones['tail_1'].matrix = (
        Matrix.Translation(tail_pivot) @
        Matrix.Rotation(.10*math.sin(math.tau*t), 4, 'Z') @
        Matrix.Translation(-tail_pivot) @ rest['tail_1']
    )
    bpy.context.view_layer.update()
    for side, _ in targets:
        ankle = rig.pose.bones[f'leg_front_{side}_3']
        foot = rig.pose.bones[f'leg_front_{side}_4']
        placed = rest[foot.name].copy()
        placed.translation = ankle.tail
        foot.matrix = placed
    for side in ('left', 'right'):
        ankle = rig.pose.bones[f'leg_back_{side}_3']
        foot = rig.pose.bones[f'leg_back_{side}_4']
        planted = rest[foot.name].copy()
        planted.translation = ankle.tail
        # The whole model rolls up against the wall in Godot. Counter-rotate
        # the two hind feet so their pads remain horizontal on the floor.
        pivot = ankle.tail
        foot.matrix = Matrix.Translation(pivot) @ Matrix.Rotation(1.05, 4, 'Y') @ Matrix.Translation(-pivot) @ planted
    bpy.context.view_layer.update()
    evaluated = rig.evaluated_get(bpy.context.evaluated_depsgraph_get())
    sample = {}
    for bone in evaluated.pose.bones:
        local = bone.parent.matrix.inverted() @ bone.matrix if bone.parent else bone.matrix
        rest_local = bone.bone.parent.matrix_local.inverted() @ bone.bone.matrix_local if bone.parent else bone.bone.matrix_local
        delta = rest_local.inverted() @ local
        p, q, _ = delta.decompose()
        sample[bone.name] = [[round(v, 8) for v in p], [round(q.x, 8), round(q.y, 8), round(q.z, 8), round(q.w, 8)]]
    frames.append(sample)

out = ROOT/'cats/scratch_poses.gd'
out.write_text('extends RefCounted\n# Generated by assets/models/blender/build_scratch_poses.py\nconst DATA = '+json.dumps(frames,separators=(',',':'))+'\n',encoding='utf-8')
print('SCRATCH_POSES',out)
